def test_recorded_expensive_route_keeps_exact_result_after_memoization():
    ps=[Pool.from_json(p) for p in RECORDED['pools']]
    route=Route(tuple(RECORDED['tokens']),tuple(RECORDED['pool_order']))
    index=RouteIndex(ps,[route.tokens[0]],len(route.pools),groups=[route.pools])
    index.routes={route.key:index.routes[route.key]}
    # This is an exact arithmetic regression; production now intentionally
    # returns an earlier valid candidate when its normal time slice expires.
    config=load_config();config['policy']['max_quote_ms']=10_000
    out=evaluate(index,config,RECORDED['header'])
    candidate=out['candidates'][0]
    assert candidate['amount_in']==RECORDED['original_amount']
    assert candidate['amount_out']==RECORDED['expected_output']
    assert candidate['net_after_modelled_cost']==RECORDED['expected_net']


def test_recorded_expired_candidate_can_be_refreshed_within_its_deadline(monkeypatch):
    config=load_config();config['policy'].update(cycle_pages=False,activity_priority=False,universe_refresh_seconds=100,pending_poll_interval_seconds=.01)
    route=Route(tuple(RECORDED['tokens']),tuple(RECORDED['pool_order']))
    ps=[Pool.from_json(p) for p in RECORDED['pools']]
    states={p.address:p for p in ps}
    previous={'route_key':route.key,'amount_in':RECORDED['original_amount'],'tokens':list(route.tokens),'pools':list(route.pools),'status':'quoted_only'}
    class FreshFeed:
        def __init__(self,rpc,local,saved):self.pools=saved['pools']
        def poll(self,**kwargs):
            now=time.monotonic_ns()
            return StateFrame(RECORDED['header'],RECORDED['header'],RECORDED['pools'],now-400_000_000,now,time.time(),52491435,0)
    monkeypatch.setattr('searcher.candidate_refresh.StateFeed',FreshFeed)
    def forbidden(*args,**kwargs):raise AssertionError('fast path repeated expensive optimization')
    monkeypatch.setattr('searcher.candidate_refresh.evaluate',forbidden)
    candidate,states,anchor,deadline,evidence=refresh_candidate(None,config,route,states,previous_candidate=previous)
    assert candidate['net_after_modelled_cost']==RECORDED['expected_net']
    assert candidate['amount_out']==route.quote(states,candidate['amount_in'])[0]
    assert time.monotonic_ns()<deadline
    assert evidence['decision']['decision_age_ms']<config['policy']['snapshot_max_age_ms']
    assert candidate['sizing_mode']=='previous_amount_repriced'
